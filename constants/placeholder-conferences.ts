export const CONFERENCE_PORTFOLIO_ANALYTICS: ConferenceAnalytics = buildPortfolioAnalytics(CONFERENCES);

function buildConferenceRelationships(conferences: ConferenceRecord[]): ConferenceRelationships {
  const projects = WORKSPACE_PROJECTS.slice(0, 6).map((project) => ({
    id: project.id,
    title: project.name,
    detail: `Status: ${project.status}`,
  }));

  const datasets = DATASETS.slice(0, 6).map((dataset) => ({
    id: dataset.id,
    title: dataset.title,
    detail: dataset.doi,
  }));

  const manuscripts = MANUSCRIPTS.map((manuscript) => ({
    id: manuscript.id,
    title: manuscript.title,
    detail: `Status: ${manuscript.status}`,
  }));

  const publications = WORKSPACE_PUBLICATIONS.map((publication) => ({
    id: `pub-${publication.doi}`,
    title: publication.title,
    detail: `${publication.journal} · ${publication.year} · ${publication.doi}`,
  }));

  const researcherIds = new Set<string>();
  MANUSCRIPTS.forEach((manuscript) => {
    manuscript.authors.forEach((author) => researcherIds.add(author.said));
  });
  DATASETS.forEach((dataset) => {
    dataset.contributors.forEach((contributor) => researcherIds.add(contributor.said));
  });

  const institutions = new Set<string>();
  conferences.forEach((conference) => {
    if (conference.institution) institutions.add(conference.institution);
  });
  MANUSCRIPTS.forEach((manuscript) => {
    manuscript.authors.forEach((author) => institutions.add(author.institution));
  });
  DATASETS.forEach((dataset) => {
    institutions.add(dataset.institution);
  });

  const grants = new Map<string, { title: string; detail: string }>();
  MANUSCRIPTS.forEach((manuscript) => {
    manuscript.relationships.grants.forEach((grant) => {
      grants.set(grant.id, { title: grant.title, detail: grant.detail ?? 'Grant funded research' });
    });
  });

  const researchers = [...researcherIds].map((said) => {
    const author = MANUSCRIPTS.flatMap((manuscript) => manuscript.authors).find(
      (entry) => entry.said === said
    );
    const contributor = DATASETS.flatMap((dataset) => dataset.contributors).find(
      (entry) => entry.said === said
    );
    return {
      id: said,
      title: author?.name ?? contributor?.name ?? said,
      detail: said,
    };
  });

  return {
    projects,
    datasets,
    manuscripts,
    publications,
    researchers,
    institutions: [...institutions].map((name) => ({
      id: `inst-${name}`,
      title: name,
      detail: 'Affiliated institution',
    })),
    funding: [...grants.entries()].map(([id, grant]) => ({
      id,
      title: grant.title,
      detail: grant.detail,
    })),
  };
}

export const CONFERENCE_RELATIONSHIPS: ConferenceRelationships = buildConferenceRelationships(CONFERENCES);
