function makeConference(overrides: Partial<ConferenceRecord>): ConferenceRecord {
  const base = createConferenceProfile({});
  const merged = {
    ...base,
    tracks: [],
    acceptedPapers: [],
    sessions: [],
    keynoteSpeakers: [],
    workshops: [],
    tutorials: [],
    sessionChairs: [],
    bestPaperAwards: [],
    travelGrants: [],
    ...overrides,
  };

  return {
    ...merged,
    analytics: overrides.analytics ?? {
      conferenceId: merged.conferenceId,
      totalSubmissions: merged.acceptedPapers.length + 12,
      totalAccepted: merged.acceptedPapers.length,
      acceptanceRate: 31,
      totalAttendees: 340,
      registeredAttendees: 260,
      countriesRepresented: 26,
      keynoteCount: merged.keynoteSpeakers.length,
      paperCount: merged.acceptedPapers.length,
      workshopCount: merged.workshops.length,
      tutorialCount: merged.tutorials.length,
      demoCount: merged.acceptedPapers.filter((paper) => paper.submissionType === 'Demo').length,
      totalSponsors: merged.sponsors.length,
      travelGrantsAwarded: merged.travelGrants.length,
      bestPaperAwards: merged.bestPaperAwards.length,
    },
  };
}

