const PRIMARY_CURRENCY: CurrencyCode = 'GBP';

function buildFundingStatistics(): FundingStatistics {
  const opportunities = FUNDING_OPPORTUNITIES;
  const grants = FUNDING_GRANTS;
  const open = opportunities.filter((opportunity) => opportunity.status === 'open');
  const upcoming = opportunities.filter((opportunity) => opportunity.status === 'upcoming');
  const awarded = grants.filter((grant) => grant.awardedAmount !== undefined);
  const totalAwarded = awarded.reduce((sum, grant) => sum + (grant.awardedAmount ?? 0), 0);
  const totalRequested = grants.reduce((sum, grant) => sum + (grant.requestedAmount ?? 0), 0);
  const active = grants.filter((grant) => grant.status === 'awarded');
  const pending = grants.filter(
    (grant) =>
      grant.applicationStage === 'drafting' ||
      grant.applicationStage === 'submitted' ||
      grant.applicationStage === 'under-review'
  );
  const countries = new Set(opportunities.flatMap((opportunity) => opportunity.countries));
  const continents = new Set(opportunities.flatMap((opportunity) => opportunity.continents));
  const disciplines = new Set(opportunities.flatMap((opportunity) => opportunity.researchAreas));
  const categories = new Set(opportunities.map((opportunity) => opportunity.category));
  const careerStages = new Set(opportunities.map((opportunity) => opportunity.careerStage));
  const averageDuration = Math.round(
    opportunities.reduce((sum, opportunity) => sum + opportunity.durationMonths, 0) /
      Math.max(1, opportunities.length)
  );
  return {
    totalOpportunities: opportunities.length,
    openOpportunities: open.length,
    upcomingOpportunities: upcoming.length,
    totalAgencies: FUNDING_AGENCIES.length,
    totalAwarded,
    totalRequested,
    activeGrants: active.length,
    pendingApplications: pending.length,
    totalCountries: countries.size,
    totalContinents: continents.size,
    totalDisciplines: disciplines.size,
    totalCategories: categories.size,
    scholarshipCount: opportunities.filter((opportunity) => opportunity.category === 'scholarship').length,
    fellowshipCount: opportunities.filter((opportunity) => opportunity.category === 'fellowship').length,
    grantCount: opportunities.filter((opportunity) => opportunity.category === 'research-grant').length,
    averageDurationMonths: averageDuration,
    averageAwardSize: awarded.length > 0 ? Math.round(totalAwarded / awarded.length) : 0,
    currency: PRIMARY_CURRENCY,
    careerStagesCovered: careerStages.size,
  };
}

function buildFundingAnalytics(): FundingAnalytics {
  const opportunities = FUNDING_OPPORTUNITIES;
  const grants = FUNDING_GRANTS;
  const open = opportunities.filter((opportunity) => opportunity.status === 'open').length;
  const upcoming = opportunities.filter((opportunity) => opportunity.status === 'upcoming').length;
  const closed = opportunities.filter((opportunity) => opportunity.status === 'closed').length;
  const awarded = grants.filter((grant) => grant.awardedAmount !== undefined);
  const totalAwarded = awarded.reduce((sum, grant) => sum + (grant.awardedAmount ?? 0), 0);
  const totalRequested = grants.reduce((sum, grant) => sum + (grant.requestedAmount ?? 0), 0);
  const successRate = grants.length > 0 ? Math.round((awarded.length / grants.length) * 100) : 0;
  const averageAwardSize = awarded.length > 0 ? Math.round(totalAwarded / awarded.length) : 0;
  const awardCategories = Array.from(new Set(grants.map((grant) => grant.category)));
  const awardsByCategory: CategoryFundingStat[] = awardCategories
    .map((category) => ({
      category,
      count: grants.filter((grant) => grant.category === category && grant.awardedAmount !== undefined).length,
      value: grants
        .filter((grant) => grant.category === category)
        .reduce((sum, grant) => sum + (grant.awardedAmount ?? 0), 0),
    }))
    .filter((stat) => stat.count > 0 || stat.value > 0);
  const agencyContinents = Array.from(new Set(FUNDING_AGENCIES.map((agency) => agency.continent)));
  const fundingByContinent: ContinentFundingStat[] = agencyContinents.map((continent) => ({
    continent,
    count: FUNDING_AGENCIES.filter((agency) => agency.continent === continent).length,
    value: grants
      .filter((grant) => AGENCY_BY_ID[grant.agencyId]?.continent === continent)
      .reduce((sum, grant) => sum + (grant.awardedAmount ?? 0), 0),
  }));
  const disciplines = Array.from(new Set(opportunities.flatMap((opportunity) => opportunity.researchAreas)));
  const applicationsByDiscipline: DisciplineApplicationStat[] = disciplines
    .map((discipline) => ({
      discipline,
      count: opportunities.filter((opportunity) => opportunity.researchAreas.includes(discipline)).length,
    }))
    .sort((a, b) => b.count - a.count);
  return {
    totalOpportunities: opportunities.length,
    openOpportunities: open,
    upcomingOpportunities: upcoming,
    closedOpportunities: closed,
    totalAgencies: FUNDING_AGENCIES.length,
    totalAwarded,
    totalRequested,
    successRate,
    averageAwardSize,
    awardCurrency: PRIMARY_CURRENCY,
    awardsByCategory,
    fundingByContinent,
    applicationsByDiscipline,
    budgetUtilisation: totalRequested > 0 ? Math.round((totalAwarded / totalRequested) * 100) : 0,
  };
}

