function makeOpportunity(seed: OpportunitySeed, index: number): FundingOpportunity {
  const agency = AGENCY_BY_ID[seed.agencyId];
  const countries = seed.countries ?? ['Global'];
  const continents = Array.from(
    new Set(countries.map((country) => (country === 'Global' ? 'Global' : continentOf(country))))
  );
  return {
    id: seed.id,
    title: seed.title,
    summary: seed.summary,
    agencyId: agency.id,
    agencyName: agency.name,
    programmeId: seed.programmeId,
    category: seed.category,
    grantType: seed.grantType,
    status: seed.status,
    careerStage: seed.careerStage,
    openedAt: seed.openedAt,
    deadline: seed.deadline,
    decisionDate: seed.decisionDate,
    durationMonths: seed.durationMonths,
    funding: seed.funding,
    eligibility: makeEligibility(seed.careerStage, seed.eligibilityOverrides),
    researchAreas: seed.researchAreas,
    countries,
    continents,
    evaluationCriteria: DEFAULT_EVALUATION,
    proposalRequirements: DEFAULT_REQUIREMENTS,
    contact: agency.contact,
    howToApply: `Applications are submitted through the ${agency.name} application portal before the stated deadline.`,
    links: linksFor(index),
    tags: seed.tags ?? [seed.category],
    createdAt: '2026-01-15',
  };
}

